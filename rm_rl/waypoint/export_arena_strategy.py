from __future__ import annotations

import argparse
import base64
import json
import zlib
from pathlib import Path

import torch


def tensor_blob(value):
    array = value.detach().cpu().half().numpy()
    return list(array.shape), base64.b85encode(array.tobytes()).decode()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--ckpt", default="rm_runs/waypoint_cls24/best.pt")
    parser.add_argument("--hold", default="/home/delphine/rm/arena-runtime/squashfs-root/resources/runtime/app/examples/claude_opus55_xhigh_2027_hold/strategy.py")
    parser.add_argument("--template", default="rm_rl/waypoint/arena_runtime_template.py")
    parser.add_argument("--out", default="/home/delphine/.config/Arena-1/workspaces/22/strategy.py")
    args = parser.parse_args()

    state = torch.load(args.ckpt, map_location="cpu", weights_only=False)
    if state.get("observation_schema", "arena307") != "arena307":
        raise SystemExit("Radar checkpoints require radar_sim; the Arena template uses arena307 inputs")
    tensors = {}
    for name, value in state["state_dict"].items():
        if not hasattr(value, "detach"):
            continue
        shape, blob = tensor_blob(value)
        tensors[name] = [shape, blob]
    payload = {
        "mean": [float(v) for v in state["mean"]],
        "std": [float(v) for v in state["std"]],
        "anchors": [[float(x), float(y)] for x, y in state["anchors"]],
        "tensors": tensors,
    }
    encoded = base64.b85encode(zlib.compress(json.dumps(payload, separators=(",", ":")).encode(), 9)).decode()
    hold = Path(args.hold).read_text(encoding="utf-8")
    template = Path(args.template).read_text(encoding="utf-8")
    if "@@PAYLOAD@@" not in template:
        raise SystemExit("template placeholder missing")
    runtime = template.replace("@@PAYLOAD@@", encoded)
    header = (
        '"""Arena 2027 sentry strategy: distilled waypoint + hold sentry low-level.\n\n'
        'Generated by rm_rl.waypoint.export_arena_strategy.  The model chooses one\n'
        'field point; the ordinary sentry drive/aim/fire logic consumes it.\n"""\n'
    )
    text = header + hold + "\n\n" + runtime
    out = Path(args.out)
    if out.exists():
        backup = out.with_suffix(".py.bak-waypoint")
        if not backup.exists():
            backup.write_bytes(out.read_bytes())
    out.write_text(text, encoding="utf-8")
    print(json.dumps({"out": str(out), "bytes": len(text.encode()), "anchors": payload["anchors"],
                      "tensors": len(tensors)}, ensure_ascii=False))


if __name__ == "__main__":
    main()
